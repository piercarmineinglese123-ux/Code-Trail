#!/usr/bin/env node
/*
 * Packs content/<course>/ into www/js/data/<course>.js
 *
 *   content/<course>/course.json            course outline
 *   content/<course>/lessons/<id>.md        theory (markdown), ends with a "## Recap" bullet list
 *   content/<course>/lessons/<id>.js        module.exports = { exercises: [ ... ] }
 *
 * Usage: node tools/build-content.js [course ...]   (default: every course folder)
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const contentDir = path.join(root, 'content');
const outDir = path.join(root, 'www', 'js', 'data');

function ser(v, indent) {
  indent = indent || '';
  const pad = indent + '  ';
  if (v instanceof RegExp) return 'new RegExp(' + JSON.stringify(v.source) + ', ' + JSON.stringify(v.flags) + ')';
  if (Array.isArray(v)) {
    if (!v.length) return '[]';
    return '[\n' + v.map((x) => pad + ser(x, pad)).join(',\n') + '\n' + indent + ']';
  }
  if (v && typeof v === 'object') {
    const keys = Object.keys(v).filter((k) => v[k] !== undefined);
    if (!keys.length) return '{}';
    return '{\n' + keys.map((k) => pad + JSON.stringify(k) + ': ' + ser(v[k], pad)).join(',\n') + '\n' + indent + '}';
  }
  return JSON.stringify(v);
}

function splitRecap(md) {
  const m = /\n##\s+Recap\s*\n([\s\S]*)$/.exec('\n' + md);
  if (!m) return { theory: md.trim(), recap: [] };
  const theory = ('\n' + md).slice(0, m.index).trim();
  const recap = m[1].split('\n').map((l) => l.trim()).filter((l) => /^[-*]\s+/.test(l)).map((l) => l.replace(/^[-*]\s+/, ''));
  return { theory, recap };
}

function buildCourse(id) {
  const dir = path.join(contentDir, id);
  const course = JSON.parse(fs.readFileSync(path.join(dir, 'course.json'), 'utf8'));
  for (const ch of course.chapters) {
    ch.lessons = ch.lessons.map((l) => {
      const base = path.join(dir, 'lessons', l.id);
      const md = fs.readFileSync(base + '.md', 'utf8');
      const { theory, recap } = splitRecap(md);
      delete require.cache[require.resolve(base + '.js')];
      const ex = require(base + '.js');
      return { id: l.id, title: l.title, theory, recap, exercises: ex.exercises };
    });
  }
  const out = '/* GENERATED by tools/build-content.js from content/' + id + ' - do not edit by hand. */\n' +
    'window.COURSES = window.COURSES || {};\nwindow.COURSES[' + JSON.stringify(id) + '] = ' + ser(course) + ';\n';
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, id + '.js'), out);
  const lessons = course.chapters.reduce((n, c) => n + c.lessons.length, 0);
  const exercises = course.chapters.reduce((n, c) => n + c.lessons.reduce((m, l) => m + l.exercises.length, 0), 0);
  console.log('built ' + id + ': ' + lessons + ' lessons, ' + exercises + ' exercises');
}

const wanted = process.argv.slice(2);
const courses = wanted.length ? wanted : fs.readdirSync(contentDir).filter((d) => fs.existsSync(path.join(contentDir, d, 'course.json')));
courses.forEach(buildCourse);
